/** Generate machine-local host configuration; never embed credentials. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { git } from './pool.mjs'

const root = fileURLToPath(new URL('../..', import.meta.url))
const target = join(root, '.codex', 'config.toml')
const marker = '# Generated by soxa agent-flow setup'
const previousMarker = '# Generated by soldy agent-flow setup'
const content = `${marker}\n[mcp_servers.clickup]\ncommand = "node"\nargs = [${JSON.stringify(join(root, 'tools', 'agent-flow', 'clickup-mcp.mjs'))}]\ncwd = ${JSON.stringify(root)}\nenv_vars = ["CLICKUP_TOKEN", "CLICKUP_CREDENTIALS_FILE", "CLICKUP_CONFIG"]\nstartup_timeout_sec = 20\ntool_timeout_sec = 120\n`
if (
	existsSync(target) &&
	![marker, previousMarker].some((value) => readFileSync(target, 'utf8').startsWith(value))
)
	throw new Error(
		'Existing project Codex configuration is not owned by setup; merge the documented MCP entry manually.',
	)
let hooks = ''
try {
	hooks = git(root, 'config', '--local', '--get', 'core.hooksPath')
} catch (failure) {
	if (failure.status !== 1) throw failure
}
if (hooks && hooks !== '.githooks')
	throw new Error('Existing Git hooksPath is configured; do not overwrite it.')
mkdirSync(join(root, '.codex'), { recursive: true })
writeFileSync(target, content)
git(root, 'config', '--local', 'core.hooksPath', '.githooks')
console.log(
	'Configured local Codex ClickUp MCP and portable Git commit hook. Restart the host to load the MCP connection.',
)
